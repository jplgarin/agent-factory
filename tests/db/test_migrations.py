import asyncio
from collections.abc import Awaitable, Callable

import asyncpg
import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from core.domain.space import Space
from db.migrate import alembic_config, upgrade
from tests.db.catalog import all_tables
from tests.db.conftest import Database


def test_models_match_the_migrated_schema(database: Database) -> None:
    try:
        command.check(alembic_config(database.url("af_owner")))
    except AutogenerateDiffsDetected as error:  # pragma: no cover
        pytest.fail(f"models and migrations differ: {error}")


async def test_downgrade_and_upgrade_round_trip(
    fresh_database: Callable[[], Awaitable[Database]],
) -> None:
    database = await fresh_database()
    config = alembic_config(database.url("af_owner"))
    await asyncio.to_thread(command.downgrade, config, "base")
    conn = await database.connect("af_owner")
    try:
        assert await all_tables(conn) == ["alembic_version"]
        assert await conn.fetchval("SELECT count(*) FROM pg_type WHERE typname = 'space'") == 0
    finally:
        await conn.close()
    await asyncio.to_thread(command.upgrade, config, "head")
    await asyncio.to_thread(command.check, config)


def test_migrations_refuse_any_role_but_af_owner(database: Database) -> None:
    for space in Space:
        with pytest.raises(RuntimeError, match="must run as af_owner"):
            upgrade(database.space_url(space))


async def test_space_roles_cannot_read_migration_state(database: Database) -> None:
    conn = await database.connect(Space.PERSONAL.db_role)
    try:
        with pytest.raises(asyncpg.InsufficientPrivilegeError):
            await conn.fetch("SELECT * FROM alembic_version")
        with pytest.raises(asyncpg.InsufficientPrivilegeError):
            await conn.execute("CREATE TABLE sneaky (space text)")
    finally:
        await conn.close()
